STOPWORDS = set(stopwords.words('english'))
NEGATION_WORDS = {'no','not','nor','neither','never','nothing',
                  'nobody','nowhere','hardly','barely','scarcely'}
STOPWORDS -= NEGATION_WORDS

def clean_text(text):
    """
    Full NLP preprocessing pipeline:
    1. Remove HTML tags
    2. Lowercase
    3. Remove special characters & numbers
    4. Remove stopwords (keeping negation)
    5. Remove extra whitespace
    """
    text = re.sub(r'<.*?>', ' ', text)
    text = text.lower()
    text = re.sub(r'http\S+|www\S+', '', text)
    text = re.sub(r'[^a-z\s]', ' ', text)
    tokens = text.split()
    tokens = [w for w in tokens if w not in STOPWORDS and len(w) > 2]
    return ' '.join(tokens)

