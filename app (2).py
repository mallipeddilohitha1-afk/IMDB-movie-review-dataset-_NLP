from sklearn.metrics import classification_report, accuracy_score, roc_auc_score
import pandas as pd

all_results = []

for name, model in [('CNN', cnn_model), ('LSTM', lstm_model), ('BiLSTM', bilstm_model)]:

    y_prob = model.predict(X_test_pad, verbose=0)

    if y_prob.shape[1] == 1:
        y_pred = (y_prob >= 0.5).astype(int).flatten()
        y_prob_flat = y_prob.flatten()
    else:
        y_pred = y_prob.argmax(axis=1)
        y_prob_flat = y_prob

    report = classification_report(y_test, y_pred, output_dict=True)

    result = {
        'Model': name,
        'Accuracy': accuracy_score(y_test, y_pred) * 100,
        'Precision (Macro)': report['macro avg']['precision'] * 100,
        'Recall (Macro)': report['macro avg']['recall'] * 100,
        'F1 (Macro)': report['macro avg']['f1-score'] * 100,
        'Precision (Weighted)': report['weighted avg']['precision'] * 100,
        'Recall (Weighted)': report['weighted avg']['recall'] * 100,
        'F1 (Weighted)': report['weighted avg']['f1-score'] * 100,
    }

    try:
        if y_prob.shape[1] == 1:
            result['ROC-AUC'] = roc_auc_score(y_test, y_prob_flat) * 100
        else:
            result['ROC-AUC'] = roc_auc_score(y_test, y_prob, multi_class='ovr') * 100
    except:
        result['ROC-AUC'] = None

    for cls in report:
        if cls not in ['accuracy', 'macro avg', 'weighted avg']:
            result[f'F1_Class_{cls}'] = report[cls]['f1-score'] * 100

